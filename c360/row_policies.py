"""Row policies on a real ClickHouse server.

chDB is embedded and does not allow CREATE USER or CREATE ROW POLICY, so this
module starts a throwaway ClickHouse server, loads the marts into it, adds one
user and one row policy per tenant, and checks what each user can see.

Set CLICKHOUSE_BIN to the clickhouse binary, or put it on PATH.
Nothing listens outside 127.0.0.1 and the server is stopped at the end.
"""
from __future__ import annotations

import json
import os
import shutil
import socket
import subprocess
import tempfile
import time
from pathlib import Path

from . import config
from .warehouse import get_session, q

MART_TABLES = ["dim_customer", "fct_calls", "fct_leads", "fct_jobs", "fct_invoices", "fct_tickets",
               "fct_memberships"]
POLICY_FILE = config.MODELS / "security" / "02_row_policies.sql"


def policy_sql(tenants=None) -> list[str]:
    tenants = tenants or [t["tenant_id"] for t in config.TENANTS]
    out = []
    for t in tenants:
        out.append(f"CREATE USER IF NOT EXISTS {t}_reader IDENTIFIED WITH plaintext_password BY '{{{{PASSWORD}}}}'")
        out.append(f"GRANT SELECT ON marts.* TO {t}_reader")
    for tbl in MART_TABLES:
        for t in tenants:
            out.append(f"CREATE ROW POLICY IF NOT EXISTS {t}_only ON marts.{tbl} "
                       f"FOR SELECT USING tenant_id = '{t}' TO {t}_reader")
        # Once a table has a policy, users with no policy see nothing. The admin needs one too.
        out.append(f"CREATE ROW POLICY IF NOT EXISTS admin_all ON marts.{tbl} FOR SELECT USING 1 TO default")
    return out


def write_policy_file() -> Path:
    head = ("-- Generated by c360/row_policies.py. For a ClickHouse server, not chDB.\n"
            "-- One reader user per tenant. Each sees only rows where tenant_id is its own.\n"
            "-- {{PASSWORD}} is filled in at deploy time. Never commit a real secret.\n")
    POLICY_FILE.write_text(head + ";\n".join(policy_sql()) + ";\n")
    return POLICY_FILE


def find_binary() -> str | None:
    for cand in [os.environ.get("CLICKHOUSE_BIN"), "/workspace/tools/clickhouse/clickhouse",
                 shutil.which("clickhouse")]:
        if cand and Path(cand).exists():
            return cand
    return None


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


class TempServer:
    def __init__(self, binary: str):
        self.binary = binary
        self.dir = Path(tempfile.mkdtemp(prefix="c360_ch_"))
        self.port = _free_port()
        self.http = _free_port()
        self.proc = None

    def __enter__(self):
        d = self.dir
        (d / "user_files").mkdir()
        (d / "config.xml").write_text(f"""<clickhouse>
  <logger><level>warning</level><log>{d}/server.log</log><errorlog>{d}/err.log</errorlog></logger>
  <listen_host>127.0.0.1</listen_host>
  <tcp_port>{self.port}</tcp_port>
  <http_port>{self.http}</http_port>
  <path>{d}/data/</path>
  <tmp_path>{d}/tmp/</tmp_path>
  <user_files_path>{d}/user_files/</user_files_path>
  <user_directories>
    <users_xml><path>users.xml</path></users_xml>
    <local_directory><path>{d}/access/</path></local_directory>
  </user_directories>
  <mark_cache_size>268435456</mark_cache_size>
</clickhouse>""")
        (d / "users.xml").write_text("""<clickhouse>
  <profiles><default/></profiles>
  <users><default><password></password><networks><ip>127.0.0.1</ip></networks>
    <profile>default</profile><quota>default</quota>
    <access_management>1</access_management></default></users>
  <quotas><default/></quotas>
</clickhouse>""")
        self.proc = subprocess.Popen([self.binary, "server", f"--config-file={d}/config.xml"],
                                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, cwd=d)
        for _ in range(120):
            try:
                self.sql("SELECT 1")
                return self
            except Exception:
                if self.proc.poll() is not None:
                    raise RuntimeError("clickhouse server exited. See " + str(d / "err.log"))
                time.sleep(0.5)
        raise RuntimeError("clickhouse server did not start in 60s")

    def sql(self, query: str, user: str = "default", password: str = "") -> str:
        res = subprocess.run([self.binary, "client", "--host", "127.0.0.1", "--port", str(self.port),
                              "--user", user, "--password", password, "--query", query],
                             capture_output=True, text=True, timeout=120)
        if res.returncode != 0:
            raise RuntimeError(res.stderr.strip()[:500])
        return res.stdout

    def __exit__(self, *exc):
        if self.proc:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=20)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        shutil.rmtree(self.dir, ignore_errors=True)


def run(binary: str | None = None) -> dict:
    binary = binary or find_binary()
    if not binary:
        return {"status": "skipped", "reason": "no clickhouse binary found"}
    write_policy_file()
    password = "local-test-only"
    get_session()
    with TempServer(binary) as srv:
        srv.sql("CREATE DATABASE marts")
        for tbl in MART_TABLES:
            pq = srv.dir / "user_files" / f"{tbl}.parquet"
            q(f"SELECT * FROM marts.{tbl} INTO OUTFILE '{pq}' FORMAT Parquet", fmt="TabSeparated")
            srv.sql(f"CREATE TABLE marts.{tbl} ENGINE = MergeTree ORDER BY tuple() "
                    f"AS SELECT * FROM file('{tbl}.parquet', Parquet)")
        for st in policy_sql():
            srv.sql(st.replace("{{PASSWORD}}", password))
        result = {"status": "ran", "server_version": srv.sql("SELECT version()").strip(), "checks": []}
        for t in config.TENANTS:
            tid = t["tenant_id"]
            for tbl in MART_TABLES:
                seen = srv.sql(f"SELECT groupUniqArray(tenant_id), count() FROM marts.{tbl} FORMAT JSONCompactEachRow",
                               user=f"{tid}_reader", password=password).strip()
                tenants_seen, n = json.loads(seen)
                expected = int(srv.sql(f"SELECT count() FROM marts.{tbl} WHERE tenant_id = '{tid}'").strip())
                # Even an explicit filter for another tenant returns nothing.
                other = int(srv.sql(f"SELECT count() FROM marts.{tbl} WHERE tenant_id != '{tid}'",
                                    user=f"{tid}_reader", password=password).strip())
                result["checks"].append({"tenant": tid, "table": tbl, "tenants_seen": sorted(tenants_seen),
                                         "rows_seen": n, "rows_expected": expected, "other_tenant_rows": other,
                                         "ok": tenants_seen in ([tid], []) and n == expected and other == 0})
        try:
            srv.sql("SELECT count() FROM marts.fct_leads", user="tnt_alpine_reader", password="wrong")
            result["wrong_password_rejected"] = False
        except RuntimeError:
            result["wrong_password_rejected"] = True
    result["all_ok"] = all(c["ok"] for c in result["checks"]) and result["wrong_password_rejected"]
    config.REPORTS.mkdir(exist_ok=True)
    (config.REPORTS / "row_policies.json").write_text(json.dumps(result, indent=2))
    return result


if __name__ == "__main__":
    r = run()
    if r["status"] == "skipped":
        print("row policies: skipped,", r["reason"])
    else:
        print(f"row policies on ClickHouse {r['server_version']}: "
              f"{sum(c['ok'] for c in r['checks'])}/{len(r['checks'])} checks passed, "
              f"wrong password rejected: {r['wrong_password_rejected']}")
        raise SystemExit(0 if r["all_ok"] else 1)
